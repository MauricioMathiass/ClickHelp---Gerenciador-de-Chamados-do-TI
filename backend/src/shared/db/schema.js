/**
 * Estrutura do banco. Roda sempre que o backend inicia: `IF NOT EXISTS`
 * cria o que falta e não mexe no que já existe.
 */
export const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
  username            TEXT NOT NULL UNIQUE,
  password_hash       TEXT NOT NULL,
  name                TEXT NOT NULL,
  role                TEXT NOT NULL,
  department          TEXT NOT NULL DEFAULT '',
  active              BOOLEAN NOT NULL DEFAULT TRUE,
  password_version    INTEGER NOT NULL DEFAULT 0,
  password_updated_at TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS chamados (
  id                 UUID PRIMARY KEY,
  assunto            TEXT NOT NULL,
  solicitante        TEXT NOT NULL,
  local              TEXT NOT NULL DEFAULT '',
  categoria          TEXT NOT NULL DEFAULT '',
  prioridade         TEXT NOT NULL,
  problema           TEXT NOT NULL,
  user_id            INTEGER,
  status             TEXT NOT NULL,
  resposta           TEXT NOT NULL DEFAULT '',
  visibility         TEXT,
  data_criacao       TIMESTAMPTZ NOT NULL,
  data_atualizacao   TIMESTAMPTZ NOT NULL,
  data_limite        TIMESTAMPTZ,
  data_fechamento    TIMESTAMPTZ,
  closed_by_username TEXT,
  closed_by_name     TEXT,
  closed_by_role     TEXT,
  sla_violado        BOOLEAN,
  auto_closed        BOOLEAN
);

CREATE INDEX IF NOT EXISTS chamados_data_criacao_idx ON chamados (data_criacao DESC);
CREATE INDEX IF NOT EXISTS chamados_solicitante_idx ON chamados (LOWER(solicitante));

CREATE TABLE IF NOT EXISTS notifications (
  id                  UUID PRIMARY KEY,
  type                TEXT NOT NULL,
  title               TEXT NOT NULL,
  message             TEXT NOT NULL,
  recipient_usernames TEXT[] NOT NULL DEFAULT '{}',
  recipient_roles     TEXT[] NOT NULL DEFAULT '{}',
  exclude_usernames   TEXT[] NOT NULL DEFAULT '{}',
  context             JSONB NOT NULL DEFAULT '{}',
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS notifications_created_at_idx ON notifications (created_at DESC);

-- Leitura e arquivamento são individuais: cada usuário tem a sua linha.
CREATE TABLE IF NOT EXISTS notification_status (
  notification_id UUID NOT NULL REFERENCES notifications (id) ON DELETE CASCADE,
  username        TEXT NOT NULL,
  read_at         TIMESTAMPTZ,
  archived_at     TIMESTAMPTZ,
  PRIMARY KEY (notification_id, username)
);

-- Configurações da empresa: um único registro (id = 1) com o documento completo.
CREATE TABLE IF NOT EXISTS settings (
  id         INTEGER PRIMARY KEY CHECK (id = 1),
  data       JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
`;
